"""
scripts/make_requirements.py

Writes requirements files pinned to the package versions installed on THIS machine,
and records your Python version for Docker.

Why: the trained model (models/*.joblib) only loads reliably with the same
scikit-learn and numpy versions that trained it. Pinning the container to your
local versions keeps the container and your model in agreement.

Run from the repo root, inside the virtual environment you trained with:
    python scripts/make_requirements.py
"""

import sys
from importlib import metadata
from pathlib import Path

API = ["fastapi", "uvicorn", "pydantic", "pandas", "numpy", "scikit-learn", "joblib", "pyyaml"]
DASHBOARD = ["streamlit", "requests", "pandas"]
DEV = ["pytest", "httpx"]


def pin(names, missing):
    lines = []
    for name in names:
        try:
            lines.append(f"{name}=={metadata.version(name)}")
        except metadata.PackageNotFoundError:
            missing.append(name)
            lines.append(name)  # unpinned fallback, so the file is still usable
    return lines


def write(path, lines, header):
    Path(path).write_text(f"# {header}\n" + "\n".join(lines) + "\n", encoding="utf8")
    print(f"wrote {path} ({len(lines)} packages)")


def main():
    missing = []
    api = pin(API, missing)
    dash = pin(DASHBOARD, missing)
    dev = pin(DEV, missing)
    everything = list(dict.fromkeys(api + dash + dev))  # union, order kept, no duplicates

    header = "generated by scripts/make_requirements.py"
    write("requirements-api.txt", api, header)
    write("requirements-dashboard.txt", dash, header)
    write("requirements.txt", everything, header)

    # Tell docker compose which Python to build with (it reads .env automatically)
    version = f"{sys.version_info.major}.{sys.version_info.minor}"
    env_path = Path(".env")
    lines = env_path.read_text(encoding="utf8").splitlines() if env_path.exists() else []
    lines = [ln for ln in lines if not ln.startswith("PYTHON_VERSION=")] + [f"PYTHON_VERSION={version}"]
    env_path.write_text("\n".join(lines) + "\n", encoding="utf8")
    print(f"wrote .env with PYTHON_VERSION={version}")

    if missing:
        print("\nWARNING: not installed here, left unpinned: " + ", ".join(missing))
        print("Install them (pip install <name>) and run this script again to pin them.")


if __name__ == "__main__":
    main()
